import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { getRepoRoot } from "#git/git.js";
import { parseVerifyYaml } from "#verify/contract.js";
import { adaptPlan } from "#verify/plan-adapters.js";

const CLI = path.join(getRepoRoot(), "dist", "cli", "index.js");

const PLAN = [
  "# Plan: greeting with a title",
  "",
  "## Implementation Plan",
  "",
  "#### Step 1.1: Greeting with a title",
  "",
  "**Files to create**:",
  "",
  "1. `src/format-greeting.js`",
  "2. `src/format-greeting.test.js`",
  "",
  "**Files to modify**: `none`",
  "",
  "**Files to delete**: `none`",
  "",
  "- Write the failing test first.",
  "",
  "#### Step 1.2: Use it",
  "",
  "**Files to create**: `none`",
  "",
  "**Files to modify**: `src/app.js`",
  "",
  "**Files to delete**:",
  "",
  "1. `src/old-greeting.js`",
  "",
].join("\n");

test("gantry adapt (lights-on): one step or the whole plan becomes allowed_paths; the contract parses (MSN-0349)", () => {
  const step = adaptPlan(PLAN, { from: "lights-on", source: "plans/a.md", step: "1.1", checks: ["node --test src/format-greeting.test.js"] });
  assert.deepEqual(step.scope, { files: ["src/format-greeting.js", "src/format-greeting.test.js"], step: "1.1" });
  const contract = parseVerifyYaml(step.verifyYaml);
  assert.deepEqual(contract.allowedPaths, ["src/format-greeting.js", "src/format-greeting.test.js"]);
  assert.ok(contract.forbiddenPaths.includes(".claude") && contract.forbiddenPaths.includes("**/package-lock.json"));
  assert.deepEqual(contract.checks.map((c) => c.run), ["node --test src/format-greeting.test.js"]);
  assert.match(step.verifyYaml, /^# Generated by gantry adapt --from lights-on from plans\/a\.md \(step 1\.1\)/);

  const all = adaptPlan(PLAN, { from: "lights-on", source: "plans/a.md", allowNew: ["src/greeting/"] });
  assert.deepEqual(all.scope.files, ["src/app.js", "src/format-greeting.js", "src/format-greeting.test.js", "src/old-greeting.js"]);
  assert.deepEqual(all.cageAllowOnly.at(-1), "src/greeting", "an allowance joins the scope without its trailing slash");
});

test("gantry adapt: unknown formats, steps and broken notation fail closed (MSN-0349)", () => {
  const bad: [string, () => unknown, RegExp][] = [
    ["format", () => adaptPlan(PLAN, { from: "spec-kit", source: "p" }), /unknown plan format spec-kit \(known: lights-on\)/],
    ["step", () => adaptPlan(PLAN, { from: "lights-on", source: "p", step: "9" }), /no step 9 in the plan \(steps: 1\.1, 1\.2\)/],
    ["no steps", () => adaptPlan("# nothing\n", { from: "lights-on", source: "p" }), /no `#### Step <n>:` heading/],
    ["list missing", () => adaptPlan(PLAN.replace("**Files to delete**: `none`", ""), { from: "lights-on", source: "p", step: "1.1" }), /step 1\.1 has no \*\*Files to delete\*\* list/],
  ];
  for (const [name, fn, pattern] of bad) assert.throws(fn, (e: Error & { code?: string }) => e.code === "GXT_ADAPT_PLAN_INVALID" && pattern.test(e.message), name);
});

test("gantry adapt CLI: verify.yaml on stdout, cage flags on stderr, --out and --json (MSN-0349)", () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "og-adapt-"));
  fs.writeFileSync(path.join(dir, "plan.md"), PLAN);
  const run = (...args: string[]) => spawnSync(process.execPath, [CLI, "adapt", ...args], { cwd: dir, encoding: "utf8" });
  const out = run("plan.md", "--from", "lights-on", "--step", "1.2");
  assert.equal(out.status, 0, out.stderr);
  assert.deepEqual(parseVerifyYaml(out.stdout).allowedPaths, ["src/app.js", "src/old-greeting.js"]);
  assert.match(out.stderr, /^adapt: cage scope: gantry cage --allow-only src\/app\.js --allow-only src\/old-greeting\.js -- <agent>$/m);
  const written = run("plan.md", "--from", "lights-on", "--out", "gen/verify.yaml");
  assert.equal(written.status, 0, written.stderr);
  assert.equal(written.stdout, "");
  assert.ok(fs.readFileSync(path.join(dir, "gen/verify.yaml"), "utf8").includes("schema: opengantry.verify.v1"));
  const json = JSON.parse(run("plan.md", "--from", "lights-on", "--step", "1.1", "--json").stdout) as { files: string[]; cage_args: string[] };
  assert.deepEqual(json.cage_args, ["--allow-only", "src/format-greeting.js", "--allow-only", "src/format-greeting.test.js"]);
  assert.equal(run("missing.md", "--from", "lights-on").status, 2);
  assert.equal(run("plan.md", "--from", "nope").status, 2);
});
