#!/usr/bin/env node
/**
 * Advisory activation checklist after `iii worker add opengantry`.
 * Does not mutate adopter .gitagent/ law or config.yaml unless --write-activation-md.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const EXAMPLE_ROOT = path.resolve(__dirname, "..");
function relFromCwd(p) {
  const rel = path.relative(process.cwd(), p);
  return rel.startsWith("..") ? p : rel || ".";
}

function readConfigWorkers(configPath) {
  if (!fs.existsSync(configPath)) return { exists: false, hasOpengantry: false, text: "" };
  const text = fs.readFileSync(configPath, "utf8");
  const hasOpengantry = /^\s*-\s*name:\s*opengantry\s*$/m.test(text);
  return { exists: true, hasOpengantry, text };
}

function activationMarkdown({ configPath, gateLine, validateLine, governedSnippet }) {
  return `# OpenGantry × iii — activation checklist

Generated by \`activate-opengantry-iii.mjs\`. Review and apply manually.

## 1. Worker in config.yaml

Ensure \`workers/opengantry\` is installed and referenced:

\`\`\`yaml
workers:
  - name: opengantry
\`\`\`

Config file checked: \`${configPath}\`

## 2. Offline validate (hot + cold + fixtures)

Run in CI before merge. Exit 0 only = pass for \`gantry verify\`.

\`\`\`bash
${validateLine}
\`\`\`

Scan root: \`workers/\` (multi-worker) or a single worker dir with top-level \`package.json\`.

Cold lint only:

\`\`\`bash
${gateLine}
\`\`\`

## 3. Governed listener (hot path)

On the port agents use, wire middleware + RBAC hooks:

\`\`\`yaml
${governedSnippet}
\`\`\`

Admission (\`auth_function_id\`) is your IdP worker — not OpenGantry.

## 4. Suggested mission fragment

\`\`\`yaml
gate_command: ${validateLine}
declared_paths:
  - workers/
\`\`\`

Planner must legislate; do not copy raw YAML into \`.gitagent/missions/\` without \`gantry legislate\`.

## 5. Order of operations

1. Cold lint clean on \`workers/\`
2. Hot verify (\`gantry::verify\`) with absolute \`repo_root\`
3. Promote-class triggers only after verdict token
`;
}

function main() {
  const writeMd = process.argv.includes("--write-activation-md");
  const configPath = path.join(EXAMPLE_ROOT, "config.yaml");
  const cfg = readConfigWorkers(configPath);
  const gateAbs = path.join(EXAMPLE_ROOT, "scripts/run-iii-architecture.mjs");
  const validateAbs = path.join(EXAMPLE_ROOT, "scripts/validate-offline.mjs");
  const gateLine = `node ${relFromCwd(gateAbs)}`;
  const validateLine = `node ${relFromCwd(validateAbs)}`;

  const governedSnippet = `  - name: iii-worker-manager
    config:
      host: 0.0.0.0
      port: 49135
      middleware_function_id: gantry::middleware
      rbac:
        auth_function_id: session::auth
        on_function_registration_function_id: gantry::on-function-registration
        on_trigger_registration_function_id: gantry::on-trigger-registration
        on_trigger_type_registration_function_id: gantry::on-trigger-type-registration`;

  console.log("OpenGantry × iii — activation checklist (advisory)\n");
  console.log("1) Worker install");
  console.log("   iii worker add ./workers/opengantry");
  if (!cfg.exists) {
    console.log(`   ⚠ config.yaml not found at ${configPath}`);
  } else if (cfg.hasOpengantry) {
    console.log(`   ✓ config.yaml lists worker name: opengantry`);
  } else {
    console.log(`   ⚠ add to config.yaml:\n      - name: opengantry`);
  }

  console.log("\n2) Offline validate (hot + cold + fixtures — bind to missions / CI)");
  console.log(`   ${validateLine}`);
  console.log("   Scan root: workers/ or single worker dir with package.json at --root");
  console.log(`   Cold lint only: ${gateLine}`);

  console.log("\n3) Governed listener snippet (hot path — copy into config.yaml):");
  console.log(governedSnippet);

  console.log("\n4) Suggested mission gate_command (Planner legislates; no silent .gitagent edits):");
  console.log(`   gate_command: ${validateLine}`);

  console.log("\n5) Order: cold lint exit 0 → gantry::verify → promote with verdict token");
  console.log("   See BEST-PRACTICES.md for exit-code semantics and wild-tree baseline.\n");

  if (writeMd) {
    const outPath = path.join(EXAMPLE_ROOT, "ACTIVATION.md");
    fs.writeFileSync(
      outPath,
      activationMarkdown({ configPath, gateLine, validateLine, governedSnippet }),
    );
    console.log(`Wrote ${outPath}`);
  }
}

main();
